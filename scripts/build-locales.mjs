import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {build} from 'esbuild';
import {fileURLToPath,pathToFileURL} from 'node:url';

const root=new URL('../',import.meta.url);
const read=path=>readFileSync(new URL(path,root),'utf8');
const parameters=text=>[...text.matchAll(/\{(\w+)\}/g)].map(match=>match[1]).filter((name,index,all)=>all.indexOf(name)===index).sort().join(',');
export function validateCatalogs(catalogs) {
  if(!catalogs.en) throw Error('locales/en.json is required as the fallback catalog');
  for(const [language,catalog] of Object.entries(catalogs)) {
    if(Intl.getCanonicalLocales(language)[0]!==language) throw Error(`Use a canonical language tag: ${language}`);
    if(!catalog||Array.isArray(catalog)||typeof catalog!=='object') throw Error(`Invalid catalog: ${language}`);
    for(const [key,value] of Object.entries(catalog)) {
      if(typeof value!=='string'||!value.trim()) throw Error(`Invalid translation: ${language}: ${key}`);
      if(!Object.hasOwn(catalogs.en,key)) throw Error(`Unknown translation key: ${language}: ${key}`);
      if(parameters(value)!==parameters(catalogs.en[key])) throw Error(`Placeholder mismatch: ${language}: ${key}`);
    }
  }
}
export async function buildLocales({check=false}={}) {
  const catalogs={};
  for(const file of readdirSync(new URL('locales/',root)).filter(file=>file.endsWith('.json')).sort()) {
    const language=file.slice(0,-5);
    const catalog=JSON.parse(read(`locales/${file}`));
    catalogs[language]=catalog;
  }
  validateCatalogs(catalogs);
  const sources=['src/plugin.ts','src/control-display.ts','src/chrome-registration.ts','src/media-model.ts','dev.local.media-controls.sdPlugin/ui/settings.js','dev.local.media-controls.sdPlugin/ui/settings.html','chrome-extension/options.js','chrome-extension/options.html','chrome-extension/background.js'];
  for(const path of sources) for(const match of read(path).matchAll(/\bt\("([^"]+)"|data-i18n="([^"]+)"/g)) {
    const key=match[1]??match[2];
    if(!Object.hasOwn(catalogs.en,key)) throw Error(`Missing English translation: ${path}: ${key}`);
  }
  const data=`// Generated by scripts/build-locales.mjs. Edit locales/*.json instead.\nexport default ${JSON.stringify(catalogs,null,2)};\n`;
  const result=await build({entryPoints:[fileURLToPath(new URL('src/localization.ts',root))],bundle:true,minify:true,charset:'utf8',format:'iife',globalName:'MediaI18n',platform:'browser',target:'chrome111',write:false,plugins:[{
    name:'locale-data',setup(build){build.onResolve({filter:/locale-data\.generated\.js$/},()=>({path:'locale-data',namespace:'catalog'}));build.onLoad({filter:/.*/,namespace:'catalog'},()=>({contents:data,loader:'ts'}));}
  }]});
  const browser='// Generated by scripts/build-locales.mjs. Do not edit.\n'+result.outputFiles[0].text;
  for(const [path,contents] of [
    ['src/locale-data.generated.ts',data],
    ['dev.local.media-controls.sdPlugin/ui/localization.js',browser],
    ['chrome-extension/localization.js',browser]
  ]) {
    if(check){if(read(path).replaceAll('\r\n','\n')!==contents) throw Error(`Stale localization output: ${path}. Run npm run locales:build.`);}
    else writeFileSync(new URL(path,root),contents);
  }
  console.log(`Localization: ${Object.keys(catalogs).join(', ')} (${Object.keys(catalogs.en).length} messages)`);
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href) await buildLocales({check:process.argv.includes('--check')});
